function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function detectTechnologies(text: string) {
  const detected = new Map<
    string,
    TechnologyDefinition & { matchedAliases: string[] }
  >();
  for (const technology of TECHNOLOGY_DICTIONARY) {
    const matchedAliases = technology.aliases.filter((alias) => {
      if (ambiguousBareAliases.has(alias.toLowerCase())) return false;
      const escaped = escapeRegExp(alias).replace(/\s+/g, "\\s+");
      return new RegExp(
        `(?<![A-Za-z0-9+#])${escaped}(?![A-Za-z0-9+#])`,
        "i",
      ).test(text);
    });
    if (matchedAliases.length && !detected.has(technology.name.toLowerCase())) {
      detected.set(technology.name.toLowerCase(), {
        ...technology,
        matchedAliases,
      });
    }
  }
  return [...detected.values()].sort((left, right) =>
    left.name.localeCompare(right.name),
  );
}

